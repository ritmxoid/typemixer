export function detectBrowserLanguage(): LanguageCode {
  if (typeof window === 'undefined' || !navigator) return 'ru';
  const navLang = (navigator.language || (navigator as any).userLanguage || 'ru').toLowerCase();
  
  if (
    navLang.startsWith('ru') ||
    navLang.startsWith('uk') ||
    navLang.startsWith('be') ||
    navLang.startsWith('kk')
  ) {
    return 'ru';
  }
  if (navLang.startsWith('es')) return 'es';
  if (navLang.startsWith('de')) return 'de';
  if (navLang.startsWith('fr')) return 'fr';
  if (navLang.startsWith('zh')) return 'zh';
  return 'en';
}

