interface LanguageContextType {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
}

const LanguageContext = createContext<LanguageContextType>({
  language: 'ru',
  setLanguage: () => {},
  t: (key, fallback) => fallback || key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<LanguageCode>(() => {
    if (typeof window !== 'undefined') {
      const stored = localStorage.getItem('textic_user_lang') as LanguageCode | null;
      if (stored && TRANSLATIONS[stored]) {
        return stored;
      }
    }
    return detectBrowserLanguage();
  });

  const setLanguage = (newLang: LanguageCode) => {
    setLanguageState(newLang);
    if (typeof window !== 'undefined') {
      try {
        localStorage.setItem('textic_user_lang', newLang);
      } catch (e) {
        console.warn('Could not save language preference:', e);
      }
    }
  };

  useEffect(() => {
    const handleLangChange = () => {
      const stored = localStorage.getItem('textic_user_lang');
      if (!stored) {
        setLanguageState(detectBrowserLanguage());
      }
    };
    window.addEventListener('languagechange', handleLangChange);
    return () => window.removeEventListener('languagechange', handleLangChange);
  }, []);

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[language] || TRANSLATIONS.ru;
    if (langDict[key]) return langDict[key];
    const fallbackDict = TRANSLATIONS.ru;
    return fallbackDict[key] || fallback || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
